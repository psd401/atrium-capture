import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import addFormats from 'ajv-formats';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaPath = path.join(root, 'apps/browser-extension/src/message.schema.json');
const outputPath = path.join(
  root,
  'apps/browser-extension/src/generated/validate-extension-message.js',
);
const declarationPath = path.join(
  root,
  'apps/browser-extension/src/generated/validate-extension-message.d.ts',
);
const checkOnly = process.argv.includes('--check');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));
const ajv = new Ajv2020({ allErrors: true, code: { esm: true, source: true }, strict: true });
addFormats(ajv, { mode: 'full' });
const validate = ajv.compile(schema);
const generated = [
  '// Generated by scripts/generate-extension-message-validator.mjs. Do not edit.',
  standaloneCode(ajv, validate),
  '',
].join('\n');
const declaration = [
  '// Generated by scripts/generate-extension-message-validator.mjs. Do not edit.',
  'declare const validate: (value: unknown) => boolean;',
  'export { validate };',
  'export default validate;',
  '',
].join('\n');

if (checkOnly) {
  const [existing, existingDeclaration] = await Promise.all([
    readFile(outputPath, 'utf8').catch(() => ''),
    readFile(declarationPath, 'utf8').catch(() => ''),
  ]);
  if (existing !== generated || existingDeclaration !== declaration) {
    throw new Error('Generated extension message validator is stale. Run pnpm messages:generate.');
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await Promise.all([writeFile(outputPath, generated), writeFile(declarationPath, declaration)]);
}
